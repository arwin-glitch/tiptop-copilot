/** Black text on a light background, white on a dark one, as Gmail pairs them. */
export function textFor(bg: string): '#000000' | '#ffffff' {
  const hex = bg.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lum = 0.2126 * r! + 0.7152 * g! + 0.0722 * b!;
  return lum > 0.6 ? '#000000' : '#ffffff';
}

export const LABEL_COLOR_GRID: readonly { bg: string; fg: string }[] = GRID_BGS.map((bg) => ({
  bg,
  fg: textFor(bg),
}));
