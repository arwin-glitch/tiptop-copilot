const ALLOWED = new Set(GMAIL_LABEL_PALETTE);

/** A colour pair the Gmail API will take. */
export function isGmailLabelColor(color: { bg: string; fg: string }): boolean {
  return ALLOWED.has(color.bg.toLowerCase()) && ALLOWED.has(color.fg.toLowerCase());
}

